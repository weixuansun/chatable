"""Context handoff assembly (.chatable/CONTEXT.md) + conclusion parsing."""
from __future__ import annotations

import os
import re
from typing import Optional

from orch.store import OrchStore

_CONTEXT_DIR = ".chatable"
_PROJECT_FILES = ("AGENTS.md", "CLAUDE.md", "README.md", "README.rst", "README")
_PROJECT_CAP = 4000
_FULL_ANCESTORS = 3
_FULL_CAP = 1500   # chars per recent ancestor conclusion
_DIFF_CAP = 8192   # parent's full diff cap

PROMPT_TEMPLATE = (
    "Read .chatable/CONTEXT.md first, then do the following instruction:\n"
    "{instruction}\n\n"
    "When finished, end your reply with a \"## Conclusion\" section with "
    "subsections: Done / Key decisions / Not done / Next steps."
)


def detect_test_cmd(wt: str) -> Optional[str]:
    """Best-effort test command for a checked-out project."""
    if os.path.isfile(os.path.join(wt, "package.json")):
        return "npm test"
    if os.path.isfile(os.path.join(wt, "go.mod")):
        return "go test ./..."
    for marker in ("pytest.ini", "conftest.py", "setup.cfg", "pyproject.toml"):
        if os.path.isfile(os.path.join(wt, marker)):
            return "python -m pytest -q"
    if os.path.isdir(os.path.join(wt, "tests")) or os.path.isdir(os.path.join(wt, "test")):
        return "python -m pytest -q"
    # Config-less pytest projects: test_*.py / *_test.py anywhere near the root.
    try:
        candidates = [os.path.join(wt, n) for n in os.listdir(wt)]
        for sub in ("src", "lib"):
            subdir = os.path.join(wt, sub)
            if os.path.isdir(subdir):
                candidates.extend(os.path.join(subdir, n) for n in os.listdir(subdir))
    except OSError:
        candidates = []
    for path in candidates:
        name = os.path.basename(path)
        if os.path.isfile(path) and (name.startswith("test_") or name.endswith("_test.py")) \
                and name.endswith(".py"):
            return "python -m pytest -q"
    makefile = os.path.join(wt, "Makefile")
    if os.path.isfile(makefile):
        try:
            with open(makefile, encoding="utf-8", errors="replace") as fh:
                if re.search(r"^test\s*:", fh.read(), re.M):
                    return "make test"
        except OSError:
            pass
    return None


def _read_capped(path: str, cap: int) -> str:
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read(cap).strip()
    except OSError:
        return ""


def _files_summary(files: list[dict]) -> str:
    if not files:
        return "no file changes"
    return ", ".join(f"{f['path']} (+{f['added']}/-{f['removed']})" for f in files[:8]) \
        + (f", … +{len(files) - 8} more" if len(files) > 8 else "")


def build_context(store: OrchStore, node: dict, instruction: str,
                  test_cmd: Optional[str], wt: str,
                  merge: Optional[dict] = None,
                  parent_diff: str = "") -> str:
    """The handoff document: project layer, path layer, task layer
    (+ a merge-task layer for merge-resolution runs)."""
    parts: list[str] = ["# Task context (generated by chatable)\n"]

    # ---- project layer ----
    project: list[str] = []
    for name in _PROJECT_FILES:
        text = _read_capped(os.path.join(wt, name), _PROJECT_CAP)
        if text:
            project.append(f"### {name}\n{text}")
            break
    notes = (store.meta.get("notes") or "").strip()
    if notes:
        project.append("### Project notes\n" + notes[:_PROJECT_CAP])
    if test_cmd:
        project.append(f"Test command: `{test_cmd}` (run it at the end and keep it green)")
    if project:
        parts.append("## Project\n\n" + "\n\n".join(project))

    # ---- merge task layer ----
    if merge:
        blocks = []
        for p in merge.get("parents") or []:
            c = (p.get("conclusion") or {}).get("done") or ""
            blocks.append(f"- {p.get('instruction') or '(untitled)'}"
                          + (f"\n  Done: {c[:400]}" if c else ""))
        if blocks:
            parts.append("## Merge task — the parent changes to preserve\n\n"
                         + "\n".join(blocks))
        conflict_files = merge.get("conflict_files") or []
        if conflict_files:
            parts.append("### Files with conflict markers\n\n"
                         + "\n".join(f"- {f}" for f in conflict_files))
        if merge.get("test_output"):
            parts.append("### Failing test output\n\n```\n"
                         + str(merge["test_output"])[:2000] + "\n```")

    # ---- path layer (all ancestors, merge-aware) ----
    anc = [n for n in store.ancestors_of(node["id"]) if not n.get("root")]
    if anc:
        lines = []
        for n in anc[:-_FULL_ANCESTORS] if len(anc) > _FULL_ANCESTORS else []:
            done = (n.get("conclusion") or {}).get("done") or ""
            lines.append(f"- {n.get('instruction') or '(untitled)'} → "
                         f"{' '.join(done.split())[:120]}")
        if lines:
            parts.append("## Path so far (older steps, one line each)\n\n" + "\n".join(lines))
        recent = anc[-_FULL_ANCESTORS:]
        blocks = []
        for n in recent:
            c = n.get("conclusion") or {}
            facts = n.get("facts") or {}
            block = [f"### {n.get('instruction') or '(untitled)'}"]
            if c.get("done"):
                block.append("Done: " + c["done"][:_FULL_CAP])
            if c.get("decisions"):
                block.append("Key decisions: " + c["decisions"][:_FULL_CAP // 2])
            if c.get("not_done"):
                block.append("Not done: " + c["not_done"][:_FULL_CAP // 2])
            if c.get("next"):
                block.append("Next steps: " + c["next"][:_FULL_CAP // 2])
            block.append("Files changed: " + _files_summary(facts.get("files") or []))
            blocks.append("\n".join(block))
        parts.append("## Path so far (most recent, full conclusions)\n\n" + "\n\n".join(blocks))
    if parent_diff:
        parts.append("## Diff of the state you start from (vs its parent)\n\n```diff\n"
                     + parent_diff[:_DIFF_CAP] + "\n```")

    # ---- task layer ----
    parts.append("## Task\n\n" + instruction)
    return "\n\n".join(parts) + "\n"


def write_context(store: OrchStore, node: dict, instruction: str,
                  test_cmd: Optional[str], wt: str,
                  merge: Optional[dict] = None,
                  parent_diff: str = "") -> str:
    """Write .chatable/CONTEXT.md into the run worktree; returns its path."""
    ctx_dir = os.path.join(wt, _CONTEXT_DIR)
    os.makedirs(ctx_dir, exist_ok=True)
    path = os.path.join(ctx_dir, "CONTEXT.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(build_context(store, node, instruction, test_cmd, wt,
                               merge=merge, parent_diff=parent_diff))
    return path


# --------------------------------------------------------------------------- #
# Conclusion parsing
# --------------------------------------------------------------------------- #

_HEAD_RE = re.compile(
    r"^#{0,4}\s*(?:conclusion|结论|总结)\s*:?\s*$",
    re.IGNORECASE | re.MULTILINE)
_FIELD_ONLY_RE = re.compile(
    r"^\s*(?:[-*]\s*)?(?:#{1,4}\s*)?(?:\*\*|__)?"
    r"(done|key decisions|not done|next steps)\s*(?:\*\*|__)?\s*:?\s*$",
    re.IGNORECASE)
_FIELD_INLINE_RE = re.compile(
    r"^\s*(?:[-*]\s*)?(?:#{1,4}\s*)?(?:\*\*|__)?"
    r"(done|key decisions|not done|next steps)\s*(?:\*\*|__)?\s*:\s*(.+?)\s*$",
    re.IGNORECASE)
_FIELD_KEYS = {"done": "done", "key decisions": "decisions",
               "not done": "not_done", "next steps": "next"}


def parse_conclusion(final_text: str) -> dict:
    """Extract the structured conclusion from an agent's final reply.

    Tolerant of heading styles (### Done, **Done**, - Done, Done:) and of a
    missing section entirely (fallback: the whole text is ``done``).
    """
    out = {"done": "", "decisions": "", "not_done": "", "next": ""}
    text = (final_text or "").strip()
    if not text:
        return out
    heads = list(_HEAD_RE.finditer(text))
    if not heads:
        out["done"] = text
        return out
    section = text[heads[-1].end():]
    parts: list[tuple[str, str]] = []
    cur: Optional[str] = None
    buf: list[str] = []

    def flush() -> None:
        nonlocal cur, buf
        if cur is not None:
            parts.append((cur, "\n".join(buf).strip()))
        cur, buf = None, []

    for line in section.splitlines():
        m = _FIELD_INLINE_RE.match(line)
        if m:
            flush()
            parts.append((_FIELD_KEYS[m.group(1).lower()], m.group(2).strip()))
            continue
        m = _FIELD_ONLY_RE.match(line)
        if m:
            flush()
            cur = _FIELD_KEYS[m.group(1).lower()]
            continue
        if cur is not None:
            buf.append(line)
    flush()

    if not parts:
        out["done"] = section.strip() or text
        return out
    for key, value in parts:
        out[key] = value
    if not out["done"]:
        out["done"] = text[:400]
    return out
